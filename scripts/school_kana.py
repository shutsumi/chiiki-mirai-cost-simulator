PREFIX = re.compile(r"^(?:(?:" + PREFS + r")立?|[^\s]{1,4}?[市町村]立)")


def label_of(name):
    return PREFIX.sub("", name).strip()


def main():
    schools = json.loads((ROOT / "data/schools_cost_data.json").read_text())
    out, missing = {}, []
    for s in schools:
        label = label_of(s["name"])
        if label not in KANA:
            missing.append((s["name"], label))
            continue
        out[s["id"]] = {"label": label, "kana": KANA[label]}
    if missing:
        raise SystemExit(f"読みがなが未登録: {missing}")
    (ROOT / "data/school_kana.json").write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print("schools:", len(out))


if __name__ == "__main__":
    main()
